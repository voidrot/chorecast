// Generates the bundled avatar set (DiceBear "Pixel Art", CC0 1.0) as static SVGs, plus the ID
// lists the web app and server use. Run with `mise run gen:avatars`; the output is committed.
// Fixed seeds keep the set stable: changing them changes every kid's avatar.
import { mkdirSync, writeFileSync } from 'node:fs'
import { createAvatar } from '@dicebear/core'
import * as pixelArt from '@dicebear/pixel-art'

const count = 24
const backgrounds = ['b6e3f4', 'c0aede', 'd1d4f9', 'ffd5dc', 'ffdfbf', 'c1f0c1']
const root = new URL('..', import.meta.url)

const ids = []
mkdirSync(new URL('public/avatars/', root), { recursive: true })
for (let i = 1; i <= count; i++) {
  const id = `pixel-${String(i).padStart(2, '0')}`
  const svg = createAvatar(pixelArt, {
    seed: `chorecast-${i}`,
    backgroundColor: [backgrounds[i % backgrounds.length]],
    radius: 50,
  }).toString()
  writeFileSync(new URL(`public/avatars/${id}.svg`, root), `${svg}\n`)
  ids.push(id)
}

const header = 'Code generated by web/scripts/gen-avatars.mjs; DO NOT EDIT.'
writeFileSync(
  new URL('src/avatars.ts', root),
  `// ${header}\n\n/** Built-in avatars, served from /avatars/<id>.svg. */\nexport const avatarIds = ${JSON.stringify(ids, null, 2).replaceAll('"', "'")} as const\n`,
)
writeFileSync(
  new URL('../server/internal/kids/avatars_gen.go', root),
  `// ${header}\n\npackage kids\n\n// AvatarIDs are the built-in avatars (web/public/avatars/<id>.svg).\nvar AvatarIDs = []string{\n${ids.map((id) => `\t"${id}",`).join('\n')}\n}\n`,
)
console.log(`wrote ${ids.length} avatars`)
